-- Repair lean databases created without automatic numeric IDs.
-- Existing rows and IDs are preserved. Safe to rerun, including after imports.
BEGIN;
SET LOCAL lock_timeout = '10s';

DO $$
DECLARE
    target_table text;
    sequence_name text;
    highest_id bigint;
    sequence_value bigint;
BEGIN
    FOREACH target_table IN ARRAY ARRAY[
        'nba_players', 'nba_teams', 'nba_schedule_games',
        'update_runs', 'public_injury_entries'
    ] LOOP
        -- Exclude writers while attaching/synchronizing each ID generator.
        EXECUTE format('LOCK TABLE public.%I IN ACCESS EXCLUSIVE MODE', target_table);
        IF EXISTS (
            SELECT 1 FROM information_schema.columns c
            WHERE c.table_schema = 'public' AND c.table_name = target_table
                AND c.column_name = 'id' AND c.is_identity = 'NO'
                AND c.column_default IS NULL
        ) THEN
            EXECUTE format(
                'ALTER TABLE public.%I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY',
                target_table
            );
        END IF;

        sequence_name := pg_get_serial_sequence(format('public.%I', target_table), 'id');
        IF sequence_name IS NULL THEN
            RAISE EXCEPTION 'No ID sequence found for public.%', target_table;
        END IF;
        EXECUTE format('SELECT COALESCE(MAX(id), 0) FROM public.%I', target_table)
            INTO highest_id;
        EXECUTE format('SELECT last_value FROM %s', sequence_name) INTO sequence_value;
        -- Never rewind an existing sequence, even when high IDs were deleted.
        PERFORM setval(sequence_name::regclass, GREATEST(highest_id, sequence_value, 1), true);
    END LOOP;
END $$;

COMMIT;
